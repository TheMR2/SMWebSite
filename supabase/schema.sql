-- 1. Companies (الشركات المنتجة / الموردين)
create table if not exists public.companies (
  id bigint generated by default as identity primary key,
  name text not null,
  address text default '',
  phone text default '',
  total_purchases numeric(14,2) not null default 0,
  paid_to_company numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);

-- 2. Warehouses (المخازن - مخزن واحد لكل شركة)
create table if not exists public.warehouses (
  id bigint generated by default as identity primary key,
  name text not null,
  company_id bigint references public.companies(id) on delete set null,
  opening_balance numeric(14,2) not null default 0,
  goods_value numeric(14,2) not null default 0,
  cash numeric(14,2) not null default 0,
  rep_goods numeric(14,2) not null default 0,
  rep_cash numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);

-- 3. Sales Reps (مناديب المبيعات والعهد)
create table if not exists public.sales_reps (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null default 'wholesale' check (type in ('wholesale', 'retail')),
  phone text default '',
  address text default '',
  credit_limit numeric(14,2) not null default 50000,
  debt_due_date text default '',
  warehouse_id bigint references public.warehouses(id) on delete set null,
  vehicle_name text default '',
  vehicle_number text default '',
  total_sales numeric(14,2) not null default 0,
  rep_goods numeric(14,2) not null default 0,
  rep_cash numeric(14,2) not null default 0,
  custody_items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

-- 4. Customers (العملاء)
create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null default 'wholesale' check (type in ('wholesale', 'retail')),
  monthly_limit numeric(14,2) not null default 0,
  annual_limit numeric(14,2) not null default 0,
  current_balance numeric(14,2) not null default 0,
  rep_id bigint references public.sales_reps(id) on delete set null,
  address text default '',
  phone text default '',
  created_at timestamptz not null default now()
);

-- 5. Products (المنتجات والأصناف)
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  company_id bigint references public.companies(id) on delete set null,
  category text default '',
  expiry text default '',
  unit text default 'كارتون',
  created_at timestamptz not null default now()
);

-- 6. Price Lists (قوائم الأسعار: جملة / تجزئة)
create table if not exists public.price_lists (
  id bigint generated by default as identity primary key,
  list_type text not null check (list_type in ('wholesale', 'retail')),
  product_id bigint not null references public.products(id) on delete cascade,
  price numeric(14,2) not null default 0,
  expiry text default '',
  created_at timestamptz not null default now()
);

-- 7. Price History (سجل تغييرات الأسعار)
create table if not exists public.price_history (
  id bigint generated by default as identity primary key,
  date text not null,
  product_id bigint references public.products(id) on delete set null,
  product_name text default '',
  list_type text default '',
  old_price numeric(14,2) not null default 0,
  new_price numeric(14,2) not null default 0,
  notes text default '',
  created_at timestamptz not null default now()
);

-- 8. Stock Batches (دفعات المخزون وتواريخ الصلاحية)
create table if not exists public.stock_batches (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null default '',
  company_id bigint references public.companies(id) on delete set null,
  warehouse_id bigint references public.warehouses(id) on delete set null,
  unit text not null default 'كارتون',
  qty numeric(14,2) not null default 0,
  unit_cost numeric(14,2) not null default 0,
  expiry_date text default '',
  purchase_invoice_number text default '',
  date text not null default '',
  created_at timestamptz not null default now()
);

-- 9. Invoices (سجل الفواتير المجمع)
create table if not exists public.invoices (
  id bigint generated by default as identity primary key,
  type text not null, -- 'sales' | 'return' | 'payment' | 'transfer' | 'custody' | 'purchase'
  number text not null unique,
  date text not null,
  customer_id bigint references public.customers(id) on delete set null,
  customer_name text default '',
  rep_id bigint references public.sales_reps(id) on delete set null,
  rep_name text default '',
  warehouse_id bigint references public.warehouses(id) on delete set null,
  warehouse_name text default '',
  company_id bigint references public.companies(id) on delete set null,
  company_name text default '',
  payment_type text default '',
  payment_method text default '',
  bonuses text default '',
  bonus_items jsonb not null default '[]'::jsonb,
  bonus_goods_value numeric(14,2) not null default 0,
  subtotal numeric(14,2) not null default 0,
  total_discount numeric(14,2) not null default 0,
  tax_rate numeric(6,2) not null default 0,
  tax_amount numeric(14,2) not null default 0,
  total numeric(14,2) not null default 0,
  due_date text default '',
  payment_status text default 'paid',
  return_reason text default '',
  received_by text default '',
  vehicle_name text default '',
  vehicle_number text default '',
  notes text default '',
  items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

-- 10. Customer Ledger (كشف حساب العملاء)
create table if not exists public.customer_ledger (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id) on delete cascade,
  date text not null,
  type text not null,
  ref_number text default '',
  debit numeric(14,2) not null default 0,
  credit numeric(14,2) not null default 0,
  balance_after numeric(14,2) not null default 0,
  notes text default '',
  created_at timestamptz not null default now()
);

-- 11. Warehouse Movements (سجل حركات المخازن)
create table if not exists public.warehouse_movements (
  id bigint generated by default as identity primary key,
  date text not null,
  warehouse_id bigint not null references public.warehouses(id) on delete cascade,
  type text not null,
  ref_number text default '',
  description text default '',
  qty numeric(14,2) not null default 0,
  value numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);

-- 12. Expenses (المصروفات)
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  date text not null,
  category text not null default 'petty_cash',
  type text not null default 'petty_cash',
  description text not null default '',
  amount numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);

-- 13. Company Returns (مرتجعات للشركات المنتجة)
create table if not exists public.company_returns (
  id bigint generated by default as identity primary key,
  date text not null,
  company_id bigint references public.companies(id) on delete set null,
  warehouse_id bigint references public.warehouses(id) on delete set null,
  product_id bigint references public.products(id) on delete set null,
  qty numeric(14,2) not null default 0,
  value numeric(14,2) not null default 0,
  reason text default '',
  created_at timestamptz not null default now()
);

-- 14. Cash Treasury State & Transactions (الخزنة الرئيسية وحركاتها)
create table if not exists public.cash_state (
  id integer primary key default 1 check (id = 1),
  opening_balance numeric(14,2) not null default 0,
  balance numeric(14,2) not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.cash_transactions (
  id bigint generated by default as identity primary key,
  date text not null,
  type text not null check (type in ('incoming', 'outgoing')),
  category text not null default 'general',
  description text default '',
  amount numeric(14,2) not null default 0,
  balance numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);

-- 15. App Users (مستخدمو النظام وصلاحياتهم)
create table if not exists public.app_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password text not null default '1234',
  name text not null,
  role text not null default 'sales-rep',
  rep_id bigint references public.sales_reps(id) on delete set null,
  rep_type text,
  phone text default '',
  address text default '',
  allowed_sections jsonb,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now()
);

-- ============================================================================
-- Row Level Security (RLS)
-- Note: For initial setup & testing with the anon key, permissive policies
-- are enabled below. Tighten these once Supabase Auth (JWT) is enforced.
-- ============================================================================
do $$
declare
  tbl text;
  tables text[] := array[
    'companies', 'warehouses', 'sales_reps', 'customers', 'products',
    'price_lists', 'price_history', 'stock_batches', 'invoices',
    'customer_ledger', 'warehouse_movements', 'expenses',
    'company_returns', 'cash_state', 'cash_transactions', 'app_users'
  ];
begin
  foreach tbl in array tables loop
    execute format('alter table public.%I enable row level security;', tbl);
    execute format('drop policy if exists "Allow full access for now" on public.%I;', tbl);
    execute format('create policy "Allow full access for now" on public.%I for all using (true) with check (true);', tbl);
  end loop;
end $$;

-- ============================================================================
-- Atomic RPC: Create Sales Invoice in a single DB Transaction
-- Ensures warehouse, customer, sales rep, cash, ledger, and invoice stay in sync.
-- ============================================================================
create or replace function public.rpc_create_sales_invoice(payload jsonb)
returns jsonb
language plpgsql
security definer
as $$
declare
  v_customer_id bigint := (payload->>'customerId')::bigint;
  v_warehouse_id bigint := (payload->>'warehouseId')::bigint;
  v_rep_id bigint := nullif(payload->>'repId', '')::bigint;
  v_payment_type text := coalesce(payload->>'paymentType', 'cash');
  v_payment_method text := coalesce(payload->>'paymentMethod', 'cash');
  v_cash_dest text := coalesce(payload->>'cashDestination', 'main_treasury');
  v_inv_number text := payload->>'number';
  v_inv_date text := coalesce(payload->>'date', to_char(now(), 'YYYY-MM-DD'));
  v_subtotal numeric := coalesce((payload->>'subtotal')::numeric, 0);
  v_discount numeric := coalesce((payload->>'totalDiscount')::numeric, 0);
  v_tax_rate numeric := coalesce((payload->>'taxRate')::numeric, 0);
  v_tax_amount numeric := coalesce((payload->>'taxAmount')::numeric, 0);
  v_total numeric := coalesce((payload->>'total')::numeric, 0);
  v_bonuses text := coalesce(payload->>'bonuses', '');
  v_bonus_items jsonb := coalesce(payload->'bonusItems', '[]'::jsonb);
  v_items jsonb := coalesce(payload->'items', '[]'::jsonb);
  v_due_date text := coalesce(payload->>'dueDate', '');

  v_net_goods numeric := v_subtotal - v_discount;
  v_bonus_val numeric := coalesce((payload->>'bonusGoodsValue')::numeric, 0);
  v_total_deduction numeric := v_net_goods + v_bonus_val;
  v_total_qty numeric := 0;

  v_company_id bigint;
  v_warehouse_name text;
  v_customer_name text;
  v_rep_name text;
  v_cust_balance numeric;
  v_cash_balance numeric;
  v_invoice_id bigint;
begin
  select coalesce(sum((item->>'qty')::numeric), 0)
  into v_total_qty
  from jsonb_array_elements(v_items) as item;

  select company_id, name into v_company_id, v_warehouse_name
  from public.warehouses where id = v_warehouse_id;

  select name, current_balance into v_customer_name, v_cust_balance
  from public.customers where id = v_customer_id;

  if v_rep_id is not null then
    select name into v_rep_name from public.sales_reps where id = v_rep_id;
  end if;

  -- A. Update Warehouse
  update public.warehouses
  set
    goods_value = case when v_rep_id is null then greatest(0, goods_value - v_total_deduction) else goods_value end,
    rep_goods = case when v_rep_id is not null then greatest(0, rep_goods - v_total_deduction) else rep_goods end,
    cash = cash + case when v_payment_type = 'cash' and v_cash_dest = 'warehouse_cash' then v_total else 0 end
  where id = v_warehouse_id;

  -- B. Warehouse Movement
  insert into public.warehouse_movements (date, warehouse_id, type, ref_number, description, qty, value)
  values (
    v_inv_date,
    v_warehouse_id,
    'صرف مبيعات',
    v_inv_number,
    format('فاتورة مبيعات (%s) للعميل: %s', case when v_payment_type = 'cash' then 'كاش' else 'آجل' end, coalesce(v_customer_name, '')),
    v_total_qty,
    v_net_goods
  );

  -- C. Update Customer Balance & Ledger
  if v_payment_type = 'credit' then
    v_cust_balance := coalesce(v_cust_balance, 0) + v_total;
    update public.customers set current_balance = v_cust_balance where id = v_customer_id;
  end if;

  insert into public.customer_ledger (customer_id, date, type, ref_number, debit, credit, balance_after, notes)
  values (
    v_customer_id,
    v_inv_date,
    case when v_payment_type = 'cash' then 'فاتورة مبيعات كاش' else 'فاتورة مبيعات آجل' end,
    v_inv_number,
    v_total,
    case when v_payment_type = 'cash' then v_total else 0 end,
    coalesce(v_cust_balance, 0),
    format('مبيعات من %s', coalesce(v_warehouse_name, ''))
  );

  -- D. Update Sales Rep
  if v_rep_id is not null then
    update public.sales_reps
    set
      total_sales = total_sales + v_total,
      rep_goods = greatest(0, rep_goods - v_total_deduction),
      rep_cash = rep_cash + case when v_payment_type = 'cash' and v_cash_dest = 'rep_cash' then v_total else 0 end
    where id = v_rep_id;
  end if;

  -- E. Update Main Treasury
  if v_payment_type = 'cash' and (v_cash_dest = 'main_treasury' or v_cash_dest = '') then
    update public.cash_state
    set balance = balance + v_total, updated_at = now()
    where id = 1
    returning balance into v_cash_balance;

    insert into public.cash_transactions (date, type, category, description, amount, balance)
    values (
      v_inv_date,
      'incoming',
      'sales',
      format('تحصيل فاتورة مبيعات كاش رقم %s - %s', v_inv_number, coalesce(v_customer_name, '')),
      v_total,
      coalesce(v_cash_balance, 0)
    );
  end if;

  -- F. Save Invoice Snapshot
  insert into public.invoices (
    type, number, date, customer_id, customer_name, rep_id, rep_name,
    warehouse_id, warehouse_name, company_id, payment_type, payment_method,
    bonuses, bonus_items, bonus_goods_value, subtotal, total_discount,
    tax_rate, tax_amount, total, due_date, payment_status, items
  )
  values (
    'sales', v_inv_number, v_inv_date, v_customer_id, coalesce(v_customer_name, ''),
    v_rep_id, coalesce(v_rep_name, 'غير محدد'),
    v_warehouse_id, coalesce(v_warehouse_name, ''), v_company_id,
    v_payment_type, v_payment_method, v_bonuses, v_bonus_items, v_bonus_val,
    v_subtotal, v_discount, v_tax_rate, v_tax_amount, v_total,
    case when v_payment_type = 'credit' then v_due_date else '' end,
    case when v_payment_type = 'cash' then 'paid' else 'unpaid' end,
    v_items
  )
  returning id into v_invoice_id;

  return jsonb_build_object('ok', true, 'invoiceId', v_invoice_id, 'number', v_inv_number);
end;
$$;
